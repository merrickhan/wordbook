import type { Database } from './db.js';

// Arbitrary constants for transaction-scoped advisory locks.
export const SCHEMA_LOCK = 0x77620001;
export const WRITE_LOCK = 0x77620002;

// `created` stays TEXT so the exact UTC ISO string from saves and backups round-trips unchanged.
// Identity columns are INTEGER so drivers return plain JavaScript numbers.
const statements = [
  `CREATE TABLE IF NOT EXISTS categories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    normalized_name TEXT NOT NULL UNIQUE
  )`,
  `CREATE TABLE IF NOT EXISTS words (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word TEXT NOT NULL UNIQUE,
    phonetic TEXT NOT NULL,
    translation TEXT NOT NULL,
    pos TEXT NOT NULL,
    definition TEXT NOT NULL,
    example TEXT NOT NULL,
    source TEXT NOT NULL,
    created TEXT NOT NULL
  )`,
  `CREATE TABLE IF NOT EXISTS word_categories (
    word_id INTEGER NOT NULL REFERENCES words(id) ON DELETE CASCADE,
    category_id INTEGER NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
    PRIMARY KEY (word_id, category_id)
  )`,
  'CREATE INDEX IF NOT EXISTS word_categories_category_idx ON word_categories (category_id)',
  `CREATE TABLE IF NOT EXISTS login_failures (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    failed_at TIMESTAMPTZ NOT NULL
  )`,
  'CREATE INDEX IF NOT EXISTS login_failures_failed_at_idx ON login_failures (failed_at)',
];

const prepared = new WeakMap<Database, Promise<void>>();

/**
 * Creates missing tables once per database handle. The advisory lock keeps concurrently starting
 * function instances from racing on CREATE TABLE IF NOT EXISTS. A failure is not cached.
 */
export function ensureSchema(db: Database): Promise<void> {
  let ready = prepared.get(db);
  if (!ready) {
    ready = db.transaction('write', async tx => {
      await tx.query('SELECT pg_advisory_xact_lock($1)', [SCHEMA_LOCK]);
      for (const statement of statements) await tx.query(statement);
    });
    prepared.set(db, ready);
    ready.catch(() => {
      if (prepared.get(db) === ready) prepared.delete(db);
    });
  }
  return ready;
}
